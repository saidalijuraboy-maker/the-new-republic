const Ctx = createContext({ lang: 'en', setLang: () => {}, t: (k) => k, date: (d) => String(d) });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState('en');

  useEffect(() => {
    try {
      const s = localStorage.getItem('lang');
      if (s === 'ru' || s === 'en') setLangState(s);
    } catch (e) {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l) => {
    setLangState(l);
    try {
      localStorage.setItem('lang', l);
    } catch (e) {}
  }, []);

  const t = useCallback((k) => (DICT[lang] && DICT[lang][k]) || DICT.en[k] || k, [lang]);
  const date = useCallback((d) => new Date(d).toLocaleDateString(lang === 'ru' ? 'ru-RU' : 'en-GB'), [lang]);

  return <Ctx.Provider value={{ lang, setLang, t, date }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
